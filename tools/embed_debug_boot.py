"""Regenerate the bootloader image compiled into STM32CubeIDE Debug."""
import argparse
from pathlib import Path
import struct


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("bootloader", type=Path, help="bootloader.bin from tools/Makefile")
args = parser.parse_args()
boot = args.bootloader.read_bytes()
if not 8 <= len(boot) <= 0x2C00:
    parser.error("bootloader must fit before the installation flag")
sp, reset = struct.unpack_from("<II", boot)
if sp != 0x20005000 or not reset & 1 or not 0x08000000 <= reset < 0x08000000 + len(boot):
    parser.error("invalid bootloader vectors")

output = Path(__file__).resolve().parents[1] / "MagStrain/Bootloader/debug_boot_image.inc"
rows = [
    "    " + ", ".join(f"0x{byte:02X}" for byte in boot[offset:offset + 16]) + ","
    for offset in range(0, len(boot), 16)
]
output.write_text(
    "/* Generated by tools/embed_debug_boot.py. */\n"
    '__asm__(".global MagStrain_ResetEntry\\n"\n'
    f'        ".set MagStrain_ResetEntry, 0x{reset:08X}\\n");\n'
    "\n__attribute__((used, section(\".boot_image\")))\n"
    "static const unsigned char debug_boot_image[] = {\n"
    + "\n".join(rows)
    + "\n};\n"
    "\n__attribute__((used, section(\".install_flag\")))\n"
    "static const unsigned char debug_install_flag_page[1024] = {\n"
    "    [0 ... 1023] = 0xFF\n"
    "};\n",
    encoding="ascii",
)
